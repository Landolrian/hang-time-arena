let saved = {};
try {
  saved = JSON.parse(localStorage.getItem("grapple-tuning") || "{}");
} catch {}
export const tuning = {
  ...defaults,
  ...Object.fromEntries(
    Object.entries(saved).filter(
      ([k, v]) => k in defaults && (typeof defaults[k] === "boolean" ? typeof v === "boolean" : Number.isFinite(v)),
    ),
  ),
};
export function saveTuning() {
  localStorage.setItem("grapple-tuning", JSON.stringify(tuning));
}
export function resetTuning() {
  Object.assign(tuning, defaults);
  saveTuning();
}
